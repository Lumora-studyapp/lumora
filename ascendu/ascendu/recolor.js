const files = ['ascendu/ascendu/src/App.jsx', 'ascendu/ascendu/src/backgrounds.jsx'];

let total = 0;
for (const file of files) {
  let content = fs.readFileSync(file, 'utf8');
  let count = 0;
  for (const [from, to] of Object.entries(mapping)) {
    const re = new RegExp(from.replace('#', '#'), 'gi');
    const matches = content.match(re);
    if (matches) {
      count += matches.length;
      content = content.replace(re, to);
    }
  }
  for (const [from, to] of Object.entries(rgbTripleMapping)) {
    // Match rgba(r,g,b,alpha) preserving alpha
    const reRgba = new RegExp(`rgba\\(${from},`, 'g');
    const matchesRgba = content.match(reRgba);
    if (matchesRgba) {
      count += matchesRgba.length;
      content = content.replace(reRgba, `rgba(${to},`);
    }
    // Match rgb(r,g,b)
    const reRgb = new RegExp(`rgb\\(${from}\\)`, 'g');
    const matchesRgb = content.match(reRgb);
    if (matchesRgb) {
      count += matchesRgb.length;
      content = content.replace(reRgb, `rgb(${to})`);
    }
  }
  fs.writeFileSync(file, content);
  total += count;
  console.log(`${file}: ${count} replacements`);
}
console.log(`TOTAL: ${total}`);
